import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ingestDocs } from "../src/ingest/ingest.js";
import { createEmbeddingClient } from "../src/embeddings/create-embedding-client.js";
import { buildVectorStore } from "../src/store/vector-store.js";
import { retrieve } from "../src/retrieve.js";
import { EVAL_CASES, type EvalCase } from "./cases.js";

interface CaseResult {
  case: EvalCase;
  topComponents: string[];
  confident: boolean;
  passed: boolean;
}

interface Summary {
  date: string;
  embeddingProvider: string;
  embeddingModel: string;
  caseCount: number;
  retrievalAccuracy: number;
  correctRefusalRate: number;
}

async function main() {
  const docsRoot = fileURLToPath(
    new URL("../../00-design-system/packages/components/src", import.meta.url)
  );
  const embeddingClient = createEmbeddingClient();
  const chunks = ingestDocs(docsRoot);
  const store = await buildVectorStore(chunks, embeddingClient);

  const results: CaseResult[] = [];
  for (const evalCase of EVAL_CASES) {
    const retrieval = await retrieve(evalCase.question, store, embeddingClient, 3);
    const topComponents = retrieval.matches.map((m) => m.chunk.componentName);
    const passed =
      evalCase.expectedComponent === null
        ? !retrieval.confident
        : topComponents.includes(evalCase.expectedComponent);
    results.push({ case: evalCase, topComponents, confident: retrieval.confident, passed });
  }

  const inScope = results.filter((r) => r.case.expectedComponent !== null);
  const adversarial = results.filter((r) => r.case.expectedComponent === null);
  const rate = (rs: CaseResult[]) =>
    rs.length ? rs.filter((r) => r.passed).length / rs.length : 1;

  const summary: Summary = {
    date: process.env.EVAL_DATE ?? new Date(0).toISOString().slice(0, 10),
    embeddingProvider: embeddingClient.provider,
    embeddingModel: embeddingClient.model,
    caseCount: EVAL_CASES.length,
    retrievalAccuracy: Number(rate(inScope).toFixed(3)),
    correctRefusalRate: Number(rate(adversarial).toFixed(3)),
  };

  const isCheckMode = process.argv.includes("--check");
  const baselinePath = fileURLToPath(new URL("./baseline.json", import.meta.url));
  // No tolerance band needed here, unlike Projects 1/2: embeddings are deterministic (confirmed
  // live — see PLAN.md's M3.3 entry), so this eval has zero LLM-generation sampling noise. A
  // regression is a regression, not a coin flip.
  const REGRESSION_TOLERANCE = 0;

  if (isCheckMode) {
    const previous = JSON.parse(readFileSync(baselinePath, "utf8"));
    console.log(JSON.stringify(summary, null, 2));
    const drops = [
      previous.retrievalAccuracy - summary.retrievalAccuracy,
      previous.correctRefusalRate - summary.correctRefusalRate,
    ];
    if (drops.some((d) => d > REGRESSION_TOLERANCE)) {
      console.error("Eval scores regressed versus the checked-in baseline.");
      process.exit(1);
    }
    return;
  }

  writeFileSync(baselinePath, JSON.stringify(summary, null, 2) + "\n");

  const failures = results.filter((r) => !r.passed);
  const lines = [
    "# Eval results",
    "",
    "Regenerated by `evals/run-eval.ts` — do not hand-edit. Run `pnpm eval` to reproduce, `pnpm eval:check` to gate a PR against the last recorded baseline.",
    "",
    `- **Date:** ${summary.date}`,
    `- **Embedding provider/model:** ${summary.embeddingProvider}:${summary.embeddingModel}`,
    `- **Cases:** ${summary.caseCount} (24 real questions spanning all 14 components, 6 adversarial with no answer in this design system)`,
    "",
    "## Retrieval accuracy",
    "",
    `**${(summary.retrievalAccuracy * 100).toFixed(1)}%** — fraction of the 24 in-scope questions where the correct component's chunk appeared in the top-3 retrieved results.`,
    "",
    "## Correct-refusal rate (adversarial subset)",
    "",
    `**${(summary.correctRefusalRate * 100).toFixed(1)}%** — fraction of the 6 adversarial questions (genuinely no answer in this design system) where retrieval correctly reported low confidence rather than handing the LLM a weak match to improvise around.`,
    "",
    "## Reproducibility",
    "",
    "Unlike Projects 1/2's evals, this one has no LLM-generation step in the scored path — only embeddings, which are deterministic. Running this eval twice with no code change produces byte-identical results, confirmed during development. `eval:check` uses zero regression tolerance for that reason: a drop here means something actually changed (the chunking, the threshold, the questions), not sampling noise.",
    "",
    failures.length > 0
      ? `${failures.length} case(s) failed:\n${failures
          .map(
            (f) =>
              `- \`${f.case.id}\` "${f.case.question}": expected ${f.case.expectedComponent ?? "no match"}, got top-3 [${f.topComponents.join(", ")}]${f.confident ? "" : " (not confident)"}`
          )
          .join("\n")}`
      : "No failures.",
  ];

  writeFileSync(fileURLToPath(new URL("./results.md", import.meta.url)), lines.join("\n") + "\n");
  console.log(JSON.stringify(summary, null, 2));
}

main();
